/** `فكك`: the word's letters with spaces between them (`سيارة` → `س ي ا ر ة`). */
export function splitLetters(word) {
    return [...word.replace(/\s+/gu, '')].join(' ');
}

/** `رتب`: the word's letters shuffled (never the word itself when that is possible). */
export function scrambleWord(word, random = Math.random) {
    const letters = [...word.replace(/\s+/gu, '')];
    if (new Set(letters).size < 2) return letters.join(' ');
    for (let attempt = 0; attempt < 10; attempt += 1) {
        const copy = [...letters];
        for (let i = copy.length - 1; i > 0; i -= 1) {
            const j = Math.floor(random() * (i + 1));
            [copy[i], copy[j]] = [copy[j], copy[i]];
        }
        if (copy.join('') !== letters.join('')) return copy.join(' ');
    }
    return [...letters].reverse().join(' ');
}
